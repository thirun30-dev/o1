"""
Convert worlds/obstacle.world (Gazebo Classic) to worlds/obstacle_gz.sdf.

Gazebo Sim (Harmonic, used from Jazzy on) cannot use the Classic world as-is:
it needs explicit system plugins (physics, sensors, ...), ignores Classic's
<state> block (where the saved obstacle poses live) and does not support
Classic material scripts. Re-run after editing obstacle.world:

    python3 tools/classic_world_to_gz.py
"""

from pathlib import Path
import xml.etree.ElementTree as ET

PKG = Path(__file__).resolve().parent.parent
SRC = PKG / 'worlds' / 'obstacle.world'
DST = PKG / 'worlds' / 'obstacle_gz.sdf'

SYSTEMS = [
    ('gz-sim-physics-system', 'gz::sim::systems::Physics', None),
    ('gz-sim-user-commands-system', 'gz::sim::systems::UserCommands', None),
    ('gz-sim-scene-broadcaster-system', 'gz::sim::systems::SceneBroadcaster', None),
    ('gz-sim-sensors-system', 'gz::sim::systems::Sensors', 'ogre2'),
]

GREY = '0.5 0.5 0.5 1'


def _replace_script_materials(element):
    for material in element.iter('material'):
        script = material.find('script')
        if script is None:
            continue
        material.remove(script)
        for tag in ('ambient', 'diffuse'):
            if material.find(tag) is None:
                ET.SubElement(material, tag).text = GREY


def convert():
    """Write obstacle_gz.sdf from obstacle.world."""
    classic_world = ET.parse(SRC).getroot().find('world')

    state_poses = {}
    state = classic_world.find('state')
    if state is not None:
        for model in state.findall('model'):
            pose = model.find('pose')
            if pose is not None:
                state_poses[model.get('name')] = pose.text

    sdf = ET.Element('sdf', version='1.9')
    world = ET.SubElement(sdf, 'world', name='optimus_obstacles')

    physics = ET.SubElement(world, 'physics', name='1ms', type='ignored')
    ET.SubElement(physics, 'max_step_size').text = '0.001'
    ET.SubElement(physics, 'real_time_factor').text = '1.0'

    for filename, name, render_engine in SYSTEMS:
        plugin = ET.SubElement(world, 'plugin', filename=filename, name=name)
        if render_engine:
            ET.SubElement(plugin, 'render_engine').text = render_engine

    for tag in ('gravity', 'scene'):
        element = classic_world.find(tag)
        if element is not None:
            world.append(element)

    for light in classic_world.findall('light'):
        world.append(light)

    for model in classic_world.findall('model'):
        _replace_script_materials(model)
        name = model.get('name')
        if name in state_poses:
            pose = model.find('pose')
            if pose is None:
                pose = ET.SubElement(model, 'pose')
            pose.text = state_poses[name]
        world.append(model)

    ET.indent(sdf, space='  ')
    header = ('<?xml version="1.0"?>\n'
              '<!-- GENERATED by tools/classic_world_to_gz.py from obstacle.world'
              ' - edit that file, not this one -->\n')
    DST.write_text(header + ET.tostring(sdf, encoding='unicode') + '\n')
    print(f'wrote {DST}')


if __name__ == '__main__':
    convert()
